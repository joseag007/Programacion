package ejercicio3;

public class Ejercicio3 {

	public static void main(String[] args) {

		int num = 2;
		int contador = 1;
		
		while (contador <= 100) {
			System.out.println(num);
			num = num + 2;
			contador ++;
		}
		
		
	}
}
